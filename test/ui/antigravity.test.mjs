import { checker, crash } from "../helpers/common.mjs";
import { fakeZen, sleep } from "../helpers/fake-zen.mjs";
const { check, done } = checker();

(async () => {
  const disk = new Map(), transcripts = new Set();
  let zen = await fakeZen({ disk, transcripts, antigravity: true, prefs: { provider: "antigravity", usage: JSON.stringify({ at: Date.now(), windows: { five_hour: { utilization: 0.75 } } }) } });
  await zen.open();
  await zen.send("Hello Gemini");
  await sleep(400);
  check("Antigravity sends and streams a reply through the real adapter", zen.acp.sent.length === 1 && zen.replies().join().includes("Reply from Antigravity") && zen.spawns.length === 0);
  const first = zen.index()[0];
  check("provider and ACP session ID are saved", first.provider === "antigravity" && transcripts.has(first.sessionId));
  zen.click(zen.$(".zai-effort-btn")); await sleep(50);
  check("model menu groups the installed providers", zen.$$(".zai-menu-label").some((e) => e.textContent === "Antigravity") && zen.$('[data-provider="antigravity"][data-model="gemini-test"]'));
  check("Claude usage is hidden for Antigravity", !zen.$(".zai-send-wrap.zai-has-usage"));
  zen.click(zen.$('[data-provider="antigravity"][data-model="claude-test"]'));
  await zen.send("Switch the model");
  check("switching models stays in the same ACP conversation", zen.acp.procs.length === 1 && zen.acp.procs[0].config[0].currentValue === "claude-test");
  await zen.close();

  zen = await fakeZen({ disk, transcripts, antigravity: true });
  await zen.open(); await zen.send("Resume");
  check("reopened Antigravity chat resumes without invoking Claude", zen.acp.calls.some((m) => m.method === "session/resume" && m.params.sessionId === first.sessionId) && zen.spawns.length === 0);
  zen.click(zen.$(".zai-effort-btn")); await sleep(50);
  zen.click(zen.$('[data-provider="claude"][data-model="sonnet"]'));
  check("switching provider starts an empty chat and explains why", zen.bubbles().length === 0 && /Started a new Claude Code chat/.test(zen.$(".zai-flash").textContent));
  await zen.send("Now Claude"); await sleep(400);
  check("new provider gets its own transcript while history keeps both", zen.spawns.length === 1 && !zen.spawns[0].resume && new Set(zen.index().map((e) => e.provider)).size === 2);
  await zen.close();

  zen = await fakeZen({ antigravity: true, holdReplies: true, prefs: { provider: "antigravity" }, page: '<button id="go" onclick="this.textContent=\'Done\'">Next</button>' });
  await zen.open();
  await zen.send("Use this page", { wait: false });
  while (!zen.acp.sent.length) await sleep(10);
  let result = await zen.acp.permission("mcp_zenai_browser_read", {});
  check("browser read is allowed through the shared permission handler", result.outcome.optionId === "allow");
  const read = await zen.acp.callTool("browser_read", {});
  const text = read.result.content.filter((b) => b.type === "text").map((b) => b.text).join("\n");
  const ref = (text.match(/\[(e\d+)\] button "Next"/) || [])[1];
  check("MCP bridge reaches the actual browser tools", !!ref, text);
  const approval = zen.acp.permission("mcp_zenai_browser_click", { ref, toolSummary: "Click Next" });
  await sleep(100);
  check("browser actions show the existing approval card", !!zen.$(".zai-approval:not(.zai-done)"));
  zen.click(zen.$(".zai-approval:not(.zai-done) .zai-allow"));
  check("Allow once becomes an ACP allow_once decision", (await approval).outcome.optionId === "allow");
  const clicked = await zen.acp.callTool("browser_click", { ref });
  check("approved action executes through the same browser gate", !clicked.result.isError && clicked.result.content.some((b) => /Clicked/.test(b.text || "")));
  result = await zen.acp.permission("run_command", { CommandLine: "echo blocked" });
  check("tainted chats deny shell commands without an approval card", result.outcome.optionId === "deny" && !zen.$(".zai-approval:not(.zai-done)"));
  zen.click(zen.$(".zai-send.zai-stop")); await sleep(80);
  check("Stop sends ACP cancellation and ends the UI turn", zen.acp.calls.some((m) => m.method === "session/cancel") && !zen.$(".zai-send.zai-stop"));
  check("nothing acts after Stop", (await zen.acp.callTool("browser_click", { ref })).result.isError);
  check("no window errors", zen.errors.length === 0, zen.errors);
  await zen.close();
  zen = await fakeZen({ antigravity: true, prefs: { provider: "antigravity", "model.antigravity": "retired-model" } });
  await zen.open(); await zen.send("Use the account default");
  check("a retired model falls back before requesting an invalid configuration", zen.acp.sent.length === 1 && !zen.acp.calls.some((m) => m.method === "session/set_config_option" && m.params.value === "retired-model") && !zen.$(".zai-error"));
  await zen.close();
  done();
})().catch(crash);
